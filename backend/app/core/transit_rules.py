# backend/app/core/transit_rules.py
"""
Єдине джерело істини (Single Source of Truth) для бізнес-правил КП «Одесміськелектротранс»
щодо обідів водіїв, підготовчого часу та перезмінок/ротацій вагонів.

Дзеркальний модуль на фронтенді: src/constants/transitRules.ts — значення мають
бути ідентичними в обох файлах.
"""

# Обідня перерва рахується від явки водія (початку зміни) до моменту прибуття
# вагона на Диспетчерський пункт (ДП / ст. А) під час чергового обороту.
MIN_WORK_MINS_BEFORE_LUNCH = 240  # 4.0 год — не раніше
MAX_WORK_MINS_BEFORE_LUNCH = 330  # 5.5 год — не пізніше (обід форсується на найближчому прибутті на ДП)

# Нормативна (базова) тривалість обіду. Будь-який час понад цю норму, що виникає
# через кратність інтервалу руху на лінії, є понаднормовим і додається до тривалості зміни водія.
TRAM_STANDARD_LUNCH_MIN = 15
TROLLEY_STANDARD_LUNCH_MIN = 20

# Максимальна тривалість обіду (базова + понаднормова), щоб кратність інтервалу
# не розтягувала обід на невизначено довгий час.
MAX_LUNCH_DURATION_MIN = 45

# Підготовчий час водія перед виїздом з депо на лінію (явка -> виїзд).
TRAM_PREP_MIN = 10
TROLLEY_PREP_MIN = 19

# Час на перезмінку водіїв/ротацію вагонів на ДП (для двозмінних DOUBLE та
# розривних SPLIT нарядів). Відбувається ВИКЛЮЧНО на Диспетчерському пункті
# (ст. А) — ніколи на проміжному вузлі примикання лінії чи в депо.
DISPATCH_HANDOFF_MIN = 3


def standard_lunch_min(is_trolley: bool) -> int:
    return TROLLEY_STANDARD_LUNCH_MIN if is_trolley else TRAM_STANDARD_LUNCH_MIN


def prep_time_min(is_trolley: bool) -> int:
    return TROLLEY_PREP_MIN if is_trolley else TRAM_PREP_MIN
